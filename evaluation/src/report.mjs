// Builds REPORT.md and SVG charts from results-<size>.json files. Every number comes from those
// files; sentences about "which is best" are computed, not written by hand.
import { groupedBarSvg, COLORS } from "./charts.mjs";

const METHODS = ["keyword", "vector", "hybrid"];
const f3 = (v) => (v === null || v === undefined ? "n/a" : v.toFixed(3));
const ms = (v) => (v === null || v === undefined ? "n/a" : v.toFixed(1));
const TIE = 0.0005;
const present = (r) => METHODS.filter((m) => r.methods[m]);
const table = (header, rows) => [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

function leaders(values) {
  const best = Math.max(...values.map((v) => v[1] ?? -Infinity));
  return values.filter((v) => (v[1] ?? -Infinity) >= best - TIE).map((v) => v[0]);
}

export function buildReport(bySize, coldBySize = {}) {
  const sizes = Object.keys(bySize).map(Number).sort((a, b) => a - b);
  const charts = {};
  const L = [];
  const anyMock = sizes.some((s) => bySize[s].meta.mock);
  const K = bySize[sizes[0]].meta.config.k;

  L.push("# TRACE-X Phase 4: Retrieval Evaluation Report", "");
  if (anyMock) L.push("> **WARNING: these results come from MOCK backends used to test the pipeline. They say nothing about MySQL FULLTEXT, Qdrant or the BGE model.**", "");
  L.push("> Generated by `evaluation/scripts/report.mjs` from the results files only. Nothing in this document was typed in by hand except the fixed definitions and limitations.", "");

  L.push("## 1. What was run", "");
  L.push(table(["Size", "Records", "Queries (answerable)", "Cases", "Run finished", "MySQL", "Embedding model", "Seed"],
    sizes.map((s) => { const m = bySize[s].meta; return [s, m.records, `${m.queries} (${m.answerable_queries})`, m.cases, m.finished_at, m.mysql?.version ?? "n/a", m.embedding_model ?? "n/a", m.dataset?.seed ?? m.config.seed]; })), "");
  const c = bySize[sizes[0]].meta.config;
  L.push(`Configuration: K=${c.k}; hybrid = Reciprocal Rank Fusion (k=${c.rrf_k}) over the top ${c.depth} of the keyword and vector lists; ${c.latency.warmupPasses} warm-up pass, ${c.latency.timedPasses} timed passes over all queries; bootstrap ${c.bootstrap.iterations} resamples (seed ${c.bootstrap.seed}).`, "");
  const m0 = bySize[sizes[0]].meta.mysql;
  if (m0?.innodb_ft_min_token_size !== undefined) L.push(`MySQL FULLTEXT settings during the run: innodb_ft_min_token_size=${m0.innodb_ft_min_token_size}, innodb_ft_enable_stopword=${m0.innodb_ft_enable_stopword}. Defaults were used and not tuned.`, "");

  L.push("## 2. Metric definitions", "",
    `- **Relevance.** Each query has graded labels: 2 = the record belongs to the event the query asks about, 1 = it belongs to a related forensic concept, 0 = not relevant. "Relevant" for Precision, Recall, F1, MRR and MAP means grade 2 (a lenient grade >= 1 view is in section 4). NDCG uses the grades.`,
    `- **Precision@${K}** = relevant records in the top ${K} / ${K}. **Recall@${K}** = relevant in the top ${K} / all relevant records. **F1@${K}** = harmonic mean of the two, computed per query, then averaged.`,
    `- **MRR** = mean of 1 / rank of the first relevant record (0 if none in the top ${K}). **MAP** = mean of AP@${K}, where AP@${K} = sum of Precision@i at each relevant rank i <= ${K}, divided by min(number of relevant, ${K}).`,
    `- **NDCG@${K}** = DCG / ideal DCG with linear gain (the grade) and a log2(rank + 1) discount.`,
    "- **Aggregation.** Macro average over answerable queries (each query counts once). No-answer queries have no relevant record, so they are excluded from those means and reported in section 5.",
    "- **Duplicates.** A record counts once per ranking; every list is de-duplicated before scoring.",
    "- **Latency.** Wall-clock milliseconds for one search call, measured in the evaluation process (MySQL and Qdrant round trips and, for vector and hybrid, query embedding included). **Warm** = all queries of the timed passes after a full warm-up pass. **First call (in process)** = the first call of a method inside the main run; the methods run one after another in the same process, so this is NOT an independent cold start. **Cold start (fresh process)** = the first search call of a brand-new Node process, measured by separate probes (section 6, only if `cold.mjs` was run).", "");

  L.push("## 3. Ranking quality", "");
  for (const s of sizes) {
    const r = bySize[s];
    const ms_ = present(r);
    L.push(`### ${s} records`, "", table(["Method", `P@${K}`, `R@${K}`, `F1@${K}`, "MRR", "MAP", `NDCG@${K}`],
      ms_.map((m) => { const o = r.methods[m].quality.overall; return [m, f3(o.p), f3(o.r), f3(o.f1), f3(o.rr), f3(o.ap), f3(o.ndcg)]; })), "");
    charts[`quality-${s}.svg`] = groupedBarSvg({ title: `Ranking quality, ${s} records (K=${K})`, groups: [["P@K", "p"], ["R@K", "r"], ["F1@K", "f1"], ["MRR", "rr"], ["MAP", "ap"], ["NDCG@K", "ndcg"]].map(([label, key]) => ({ label, bars: ms_.map((m) => ({ label: m, value: r.methods[m].quality.overall[key], color: COLORS[m] })) })) });
    L.push(`![Ranking quality ${s}](charts/quality-${s}.svg)`, "");
  }

  L.push("## 4. By query category and lenient relevance", "");
  for (const s of sizes) {
    const r = bySize[s];
    const ms_ = present(r);
    const cats = Object.keys(r.methods[ms_[0]].quality.by_category);
    L.push(`### ${s} records: NDCG@${K} / Recall@${K} per category`, "",
      table(["Category", "Queries", ...ms_.map((m) => `${m} NDCG / R`), "Leader (NDCG)"],
        cats.map((cat) => [cat, r.methods[ms_[0]].quality.by_category[cat].queries, ...ms_.map((m) => { const b = r.methods[m].quality.by_category[cat]; return `${f3(b.ndcg)} / ${f3(b.r)}`; }), leaders(ms_.map((m) => [m, r.methods[m].quality.by_category[cat].ndcg])).join(", ")])), "");
    charts[`ndcg-by-category-${s}.svg`] = groupedBarSvg({ title: `NDCG@${K} by category, ${s} records`, groups: cats.map((cat) => ({ label: cat, bars: ms_.map((m) => ({ label: m, value: r.methods[m].quality.by_category[cat].ndcg, color: COLORS[m] })) })) });
    L.push(`![NDCG by category ${s}](charts/ndcg-by-category-${s}.svg)`, "",
      `Lenient relevance (grade >= 1), ${s} records:`, "",
      table(["Method", `P@${K}`, `R@${K}`, "MRR", "MAP"], ms_.map((m) => { const o = r.methods[m].quality.overall.lenient; return [m, f3(o.p), f3(o.r), f3(o.rr), f3(o.ap)]; })), "");
  }

  L.push("## 5. Queries with no relevant record", "", "Ideal behaviour is to return nothing (or nothing confident). A method that always returns K results cannot express \"no answer\" without a score threshold, which this evaluation deliberately does not add.", "",
    table(["Size", "Method", "No-answer queries", "Returned any result", "Mean results returned"], sizes.flatMap((s) => present(bySize[s]).map((m) => { const n = bySize[s].methods[m].quality.no_answer; return [s, m, n.queries, n.queries_returning_any_result, ms(n.mean_results_returned)]; }))), "");

  L.push("## 6. Latency (milliseconds)", "",
    table(["Size", "Method", "First call (in process)", "Warm mean", "Warm median", "Warm p95", "Warm samples"],
      sizes.flatMap((s) => present(bySize[s]).map((m) => { const l = bySize[s].methods[m].latency; return [s, m, ms(l.first_call_in_process_ms?.ms), ms(l.warm?.mean), ms(l.warm?.median), ms(l.warm?.p95), l.warm?.samples]; }))), "",
    "First-call numbers are single samples taken after earlier methods had already opened connections and loaded the model (hybrid runs last), so they understate a true cold start. Independent cold starts are below when available.", "");
  charts["latency-warm-median.svg"] = groupedBarSvg({ title: "Warm median latency (ms)", yMax: Math.max(10, ...sizes.flatMap((s) => present(bySize[s]).map((m) => bySize[s].methods[m].latency.warm?.median ?? 0))) * 1.15, decimals: 1, yLabel: "ms", groups: sizes.map((s) => ({ label: `${s} records`, bars: present(bySize[s]).map((m) => ({ label: m, value: bySize[s].methods[m].latency.warm?.median ?? 0, color: COLORS[m] })) })) });
  L.push("![Warm median latency](charts/latency-warm-median.svg)", "");
  for (const s of sizes) {
    const rows = present(bySize[s]).filter((m) => Object.keys(bySize[s].methods[m].latency.stages_mean_ms).length).map((m) => [m, Object.entries(bySize[s].methods[m].latency.stages_mean_ms).map(([k, v]) => `${k}=${ms(v)}`).join(", ")]);
    if (rows.length) L.push(`Mean time per stage, ${s} records:`, "", table(["Method", "Stages (ms)"], rows), "");
  }

  const coldSizes = sizes.filter((s) => coldBySize[s]);
  if (coldSizes.length) {
    L.push("### Cold start in a fresh process", "", "Every sample is the first search call of a brand-new Node process (fresh MySQL pool, Qdrant client and model load), timed after the environment checks and before the model or Qdrant are touched. The MySQL and Qdrant servers' caches and the operating-system file cache are not reset, so samples after the first start with warm servers; all samples are summarised.", "",
      table(["Size", "Method", "Samples", "First sample", "Min", "Median", "Max"],
        coldSizes.flatMap((s) => Object.entries(coldBySize[s].summary).map(([m, x]) => [s, m, x.samples, ms(x.first_sample_ms), ms(x.min_ms), ms(x.median_ms), ms(x.max_ms)]))), "");
  } else {
    L.push("Independent fresh-process cold-start measurements were not run (`node evaluation/scripts/cold.mjs --size <n>`), so no cold-start figure is reported.", "");
  }

  if (sizes.length > 1) {
    const [a, b] = [sizes[0], sizes[sizes.length - 1]];
    L.push(`## 7. ${a} vs ${b} records`, "",
      table(["Method", `NDCG@${K} ${a}`, `NDCG@${K} ${b}`, "Change", `MAP ${a}`, `MAP ${b}`, "Change", `Warm median ${a}`, `Warm median ${b}`, "Ratio"],
        METHODS.filter((m) => bySize[a].methods[m] && bySize[b].methods[m]).map((m) => {
          const x = bySize[a].methods[m], y = bySize[b].methods[m];
          return [m, f3(x.quality.overall.ndcg), f3(y.quality.overall.ndcg), f3(y.quality.overall.ndcg - x.quality.overall.ndcg), f3(x.quality.overall.ap), f3(y.quality.overall.ap), f3(y.quality.overall.ap - x.quality.overall.ap), ms(x.latency.warm.median), ms(y.latency.warm.median), (y.latency.warm.median / x.latency.warm.median).toFixed(2)];
        })), "", "The relevant records are the same in both sets; the larger set adds only non-relevant records, so this isolates the effect of corpus size on ranking.", "");
  }

  L.push("## 8. Does hybrid help? (paired bootstrap over queries)", "");
  for (const s of sizes) {
    const cmp = bySize[s].comparisons ?? {};
    if (!Object.keys(cmp).length) continue;
    const rows = [];
    const verdicts = [];
    for (const [name, metrics] of Object.entries(cmp)) {
      for (const [metric, v] of Object.entries(metrics)) {
        if (!v) continue;
        const sig = v.ci_low > 0 ? "hybrid higher" : v.ci_high < 0 ? "hybrid lower" : "no clear difference";
        rows.push([name.replace("hybrid_vs_", "hybrid - "), metric, f3(v.mean_diff), `[${f3(v.ci_low)}, ${f3(v.ci_high)}]`, v.pairs, sig]);
        if (metric === "ndcg") verdicts.push(`${s} records, NDCG@${K}, hybrid vs ${name.replace("hybrid_vs_", "")}: ${sig} (mean difference ${f3(v.mean_diff)}, 95% CI ${f3(v.ci_low)} to ${f3(v.ci_high)}).`);
      }
    }
    L.push(`### ${s} records`, "", table(["Comparison", "Metric", "Mean difference", "95% CI", "Queries", "Reading"], rows), "", ...verdicts.map((v) => `- ${v}`), "");
  }

  L.push("## 9. Observations computed from the results", "");
  for (const s of sizes) {
    const r = bySize[s];
    const ms_ = present(r);
    for (const [label, key] of [["NDCG@K", "ndcg"], ["MAP", "ap"], ["MRR", "rr"], [`Recall@${K}`, "r"], [`Precision@${K}`, "p"]]) {
      L.push(`- ${s} records, ${label}: highest = ${leaders(ms_.map((m) => [m, r.methods[m].quality.overall[key]])).join(", ")} (${ms_.map((m) => `${m} ${f3(r.methods[m].quality.overall[key])}`).join(", ")}).`);
    }
    const fast = ms_.map((m) => [m, -(r.methods[m].latency.warm?.median ?? Infinity)]);
    L.push(`- ${s} records, lowest warm median latency: ${leaders(fast).join(", ")}.`);
  }
  L.push("");

  L.push("## 10. Limitations", "",
    "- The records, queries and labels are synthetic and were written by the same author. Paraphrase records favour vector search and keyword-trap records favour neither; the results describe this benchmark, not real casework. Query/label files are in `evaluation/data/` for review.",
    "- The semantic and related-concept queries were written to avoid the record wording; `data/query-audit.json` shows how much vocabulary each query still shares with its relevant records.",
    "- Keyword search is stock InnoDB FULLTEXT in natural-language mode (no stemming, no synonyms, default token size and stopwords). A tuned search engine could behave differently.",
    "- Keyword and hybrid run as an administrator because FULLTEXT cannot run through the investigator views. Access-control behaviour is not evaluated here.",
    "- Hybrid uses Reciprocal Rank Fusion with constants fixed before the run (not tuned on these labels). Other fusion rules were not tried.",
    "- The evaluation corpus contains evidence records only. The application indexing worker also supports findings, but finding records are outside this benchmark's dataset and are not included in its ranking metrics.",
    "- Forty queries give wide confidence intervals; small differences should not be over-read.",
    "- Latency is from one machine and local services. Server and operating-system caches cannot be cleared from the scripts, so even fresh-process cold probes are a lower bound on a true cold start.",
    "- Qdrant similarity is a retrieval signal only. MySQL remains the authority for every record and relationship.", "");
  return { markdown: L.join("\n"), charts };
}
