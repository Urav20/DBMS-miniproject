// Builds the SQL that creates an isolated evaluation database from Person A's UNMODIFIED
// database/01..03 files. The files are read as text, the database name is replaced in memory,
// and the result is written under evaluation/tmp/ (git-ignored). database/ is never written.
//
// Only the bare word `tracex` is replaced (word boundary), so the accounts and roles
// (tracex_admin, tracex_worker_app, ...) and the variable @tracex_user_id stay as they are.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { assertEvalDb, EvalSafetyError } from "./safety.mjs";
import { EVIDENCE_TYPES, ADMIN_USERNAME } from "../config.mjs";

export const SOURCE_FILES = Object.freeze(["01_schema.sql", "02_access.sql", "03_routines.sql"]);

export function renameDatabase(sql, dbName) {
  assertEvalDb(dbName);
  return sql.replace(/\btracex\b/g, dbName);
}

// Fails closed if anything in the transformed script could still touch another database.
export function verifyTransformed(sql, dbName) {
  assertEvalDb(dbName);
  if (/\btracex\b/.test(sql)) throw new EvalSafetyError("Transformed SQL still mentions the database `tracex`.");

  const uses = [...sql.matchAll(/^\s*USE\s+`?([A-Za-z0-9_]+)`?\s*;/gim)].map((m) => m[1]);
  if (uses.length < 3 || uses.some((u) => u !== dbName)) {
    throw new EvalSafetyError("Every USE statement must target the evaluation database.");
  }
  const drops = [...sql.matchAll(/DROP\s+DATABASE\s+(?:IF\s+EXISTS\s+)?`?([A-Za-z0-9_]+)`?/gi)].map((m) => m[1]);
  if (drops.length !== 1 || drops[0] !== dbName) {
    throw new EvalSafetyError("The script must drop exactly one database: the evaluation database.");
  }
  const creates = [...sql.matchAll(/CREATE\s+DATABASE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?([A-Za-z0-9_]+)`?/gi)].map((m) => m[1]);
  if (creates.length !== 1 || creates[0] !== dbName) {
    throw new EvalSafetyError("The script must create exactly one database: the evaluation database.");
  }
  // Every schema-qualified GRANT target must be the evaluation database.
  const grantSchemas = [
    ...sql.matchAll(/GRANT\s[^;]*?\sON\s+(?:(?:PROCEDURE|FUNCTION|TABLE)\s+)?`?([A-Za-z0-9_]+)`?\./gi),
  ].map((m) => m[1]);
  if (grantSchemas.length < 30 || grantSchemas.some((s) => s !== dbName)) {
    throw new EvalSafetyError("Every GRANT ... ON <schema>.<object> must target the evaluation database.");
  }
  // No account-level or global changes beyond what Person A's files already do.
  if (/\b(SET\s+GLOBAL|SET\s+PERSIST|ALTER\s+USER|DROP\s+USER|DROP\s+ROLE)\b/i.test(sql)) {
    throw new EvalSafetyError("Unexpected account or global statement in the generated SQL.");
  }
  return true;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

// Evaluation seed: the minimum the schema needs before evidence can be registered.
// The admin has a placeholder hash that no bcrypt comparison can match: it cannot log in.
export function evalSeedSql(dbName) {
  assertEvalDb(dbName);
  const types = EVIDENCE_TYPES.map((t) => `(${q(t)}, 'Evaluation evidence type')`).join(",\n  ");
  return [
    `USE ${dbName};`,
    "INSERT INTO `role` (role_name) VALUES ('Administrator'), ('Investigator');",
    `INSERT INTO evidence_type (name, description) VALUES\n  ${types};`,
    "INSERT INTO app_user (role_id, username, email, full_name, password_hash, is_active)",
    `SELECT role_id, ${q(ADMIN_USERNAME)}, 'eval_admin@example.test', 'Evaluation Admin (cannot log in)', 'NOLOGIN-evaluation-only', 1`,
    "FROM `role` WHERE role_name = 'Administrator';",
    "SELECT DATABASE() AS evaluation_database_ready;",
    "",
  ].join("\n");
}

// databaseDir: the folder holding Person A's files (read only).
export function buildSetupSql({ databaseDir, dbName, read = (p) => readFileSync(p, "utf8") }) {
  assertEvalDb(dbName);
  const parts = SOURCE_FILES.map((f) => {
    const text = read(join(databaseDir, f)).replace(/\r\n/g, "\n");
    return `-- ===== ${f} (database name replaced by ${dbName}) =====\n${renameDatabase(text, dbName)}`;
  });
  const header =
    `-- GENERATED by evaluation/scripts/sql.mjs. Do not edit; do not commit.\n` +
    `-- Creates the isolated evaluation database ${dbName} (it DROPs and recreates ONLY that database).\n`;
  const sql = [header, ...parts, "-- ===== evaluation seed =====", evalSeedSql(dbName)].join("\n");
  verifyTransformed(sql, dbName);
  return sql;
}

export function buildCleanupSql(dbNames) {
  const lines = ["-- GENERATED by evaluation/scripts/sql.mjs. Removes ONLY the isolated evaluation databases."];
  for (const n of dbNames) lines.push(`DROP DATABASE IF EXISTS ${assertEvalDb(n)};`);
  lines.push("");
  return lines.join("\n");
}
